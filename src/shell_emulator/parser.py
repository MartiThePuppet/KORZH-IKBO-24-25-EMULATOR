"""Парсер команд: разделение по пробелам + раскрытие переменных окружения.

Задача парсера — превратить строку, введённую пользователем, в список
токенов (аргументов), как это делает настоящий shell. На этом этапе
(вариант №12) требуется поддержка раскрытия переменных окружения
реальной ОС вида $HOME или ${HOME}.
"""
import os
import re

# Регулярное выражение ищет вхождения вида $NAME или ${NAME}.
#   \$\w+        — $HOME, $USER, $PATH123
#   \$\{[^}]+\}  — ${HOME}, ${MY_LONG_VAR}
# Группа ( ) захватывает "внутренность" — имя переменной вместе с фигурными
# скобками, если они были. Это позволяет обрабатывать оба варианта единообразно.
_ENV_RE = re.compile(r"\$(\w+|\{[^}]+\})")


def expand_env(token: str) -> str:
    """Раскрывает $VAR и ${VAR} через окружение реальной ОС.

    Поведение как в sh: если переменная не определена, подставляется пустая
    строка. Мы намеренно не бросаем исключение, потому что в настоящем
    shell `echo $UNDEFINED` печатает пустую строку, а не ошибку.
    """

    def _sub(match: re.Match) -> str:
        # match.group(1) — то, что попало в скобки регулярки:
        # либо "HOME", либо "{HOME}".
        name = match.group(1)
        # Если были фигурные скобки — отрезаем их, оставляя чистое имя.
        if name.startswith("{") and name.endswith("}"):
            name = name[1:-1]
        # os.environ.get вернёт "" для неопределённой переменной — это
        # именно то, что нам нужно.
        return os.environ.get(name, "")
    # sub применяет _sub ко всем найденным $VAR/${VAR} в токене.
    return _ENV_RE.sub(_sub, token)


def parse(line: str) -> list[str]:
    """Разбивает строку на токены по пробелам и раскрывает env-переменные.

    Простой split() (без shlex) — требование этапа 1 для варианта №12.
    На этапе, где понадобится поддержка кавычек, парсер будет усложнён.
    """
    tokens = line.strip().split()
    # К каждому токену применяем раскрытие переменных окружения.
    return [expand_env(t) for t in tokens]

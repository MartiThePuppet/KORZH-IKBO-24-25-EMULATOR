# Точка входа для `python -m src.shell_emulator`.
# Всё, что делает этот файл — вызывает main() из cli.py.
# Логика специально вынесена в cli.py, чтобы её было проще тестировать.
from .cli import main

if __name__ == "__main__":
    # sys.exit не нужен: main() возвращает int, но Python сам завершится
    # с кодом 0, если функция ничего не вернула. Возвращаемое значение
    # (ненулевое при ошибке) в этой простой обёртке мы не транслируем,
    # потому что main() обычно вызывается напрямую в run.sh.
    main()

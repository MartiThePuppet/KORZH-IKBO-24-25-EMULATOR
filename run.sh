#!/usr/bin/env bash
# Скрипт запуска эмулятора.
# Единая точка входа, чтобы не заставлять пользователя помнить про python -m.
# set -e — при любой ошибке скрипт немедленно завершится с ненулевым кодом.
set -e

# Переходим в каталог самого скрипта: так относительные пути (-v vfs_data/...)
# будут работать независимо от того, откуда пользователь запустил run.sh.
cd "$(dirname "$0")"

# exec заменяет текущий процесс python-процессом: лишний bash не остаётся в памяти.
# "$@" — прокидываем все аргументы командной строки как есть.
exec python -m src.shell_emulator "$@"
